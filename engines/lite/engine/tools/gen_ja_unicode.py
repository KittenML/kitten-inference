"""Writes src/frontend/lang/ja_unicode_tables.inc: the Unicode tables the Japanese text front end needs (NFKC
decompositions, canonical combining classes, canonical compositions, decimal digits, str.isdigit, white space), from this
Python's unicodedata (the Unicode Character Database, Unicode License v3). Run it with the Python version whose
unicodedata the reference package uses (3.12 -> Unicode 15.0) and commit the output.

usage: python gen_ja_unicode.py OUT.inc"""
import sys
import unicodedata as ud

HANGUL = range(0xAC00, 0xD7A4)


def chars():
    for cp in range(0x110000):
        if 0xD800 <= cp < 0xE000:
            continue
        yield cp


def ranges(pred):
    out, start, prev = [], None, None
    for cp in chars():
        if pred(cp):
            if start is None:
                start = cp
            elif prev != cp - 1:
                out.append((start, prev))
                start = cp
            prev = cp
    if start is not None:
        out.append((start, prev))
    return out


decomp, data = [], []
for cp in chars():
    if cp in HANGUL:
        continue
    c = chr(cp)
    d = ud.normalize("NFKD", c)
    if d != c:
        decomp.append((cp, len(data), len(d)))
        data += [ord(x) for x in d]
ccc = []
for cp in chars():
    k = ud.combining(chr(cp))
    if k:
        if ccc and ccc[-1][2] == k and ccc[-1][1] == cp - 1:
            ccc[-1] = (ccc[-1][0], cp, k)
        else:
            ccc.append((cp, cp, k))
comp = []
for cp in chars():
    if cp in HANGUL:
        continue
    d = ud.decomposition(chr(cp))
    if not d or d.startswith("<"):
        continue
    parts = [int(x, 16) for x in d.split()]
    if len(parts) == 2 and ud.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
        comp.append((parts[0], parts[1], cp))
comp.sort()
digits = ranges(lambda cp: ud.category(chr(cp)) == "Nd")
isdigit = ranges(lambda cp: chr(cp).isdigit())
space = ranges(lambda cp: chr(cp).isspace())

with open(sys.argv[1], "w", encoding="utf-8") as f:
    w = f.write
    w(f"// Generated by engines/lite/engine/tools/gen_ja_unicode.py from Unicode {ud.unidata_version} (Python "
      f"unicodedata). Do not edit.\n")
    w(f"#define KT_JA_UNICODE_VERSION \"{ud.unidata_version}\"\n")
    w("static const uint32_t kDecomp[][3] = {  // code point, offset in kDecompData, length (NFKD, full)\n")
    for i in range(0, len(decomp), 4):
        w("    " + " ".join("{0x%X, %d, %d}," % t for t in decomp[i:i + 4]) + "\n")
    w("};\nstatic const uint32_t kDecompData[] = {\n")
    for i in range(0, len(data), 12):
        w("    " + " ".join("0x%X," % x for x in data[i:i + 12]) + "\n")
    w("};\nstatic const uint32_t kCombining[][3] = {  // first, last, canonical combining class\n")
    for i in range(0, len(ccc), 4):
        w("    " + " ".join("{0x%X, 0x%X, %d}," % t for t in ccc[i:i + 4]) + "\n")
    w("};\nstatic const uint32_t kCompose[][3] = {  // first, second -> composed (primary composites)\n")
    for i in range(0, len(comp), 4):
        w("    " + " ".join("{0x%X, 0x%X, 0x%X}," % t for t in comp[i:i + 4]) + "\n")
    w("};\nstatic const uint32_t kDigits[][2] = {  // general category Nd\n")
    for i in range(0, len(digits), 6):
        w("    " + " ".join("{0x%X, 0x%X}," % t for t in digits[i:i + 6]) + "\n")
    w("};\nstatic const uint32_t kIsDigit[][2] = {  // str.isdigit() (Numeric_Type Decimal or Digit)\n")
    for i in range(0, len(isdigit), 6):
        w("    " + " ".join("{0x%X, 0x%X}," % t for t in isdigit[i:i + 6]) + "\n")
    w("};\nstatic const uint32_t kSpaces[][2] = {  // str.isspace()\n")
    w("    " + " ".join("{0x%X, 0x%X}," % t for t in space) + "\n};\n")
print(len(decomp), len(data), len(ccc), len(comp), len(digits), len(isdigit), len(space), ud.unidata_version)
