"""python gen_wino_tables.py ../src/backend/cpu/ops/wino2_tables.hpp

Writes the Toom-Cook / Winograd 1-D transforms F(m,r) in exact rationals, written as C++ tables.
y[i] = sum_k g[k] d[i+k], i < m  ==  AT [ (G g) .* (BT d) ]  with alpha = m + r - 1 evaluation points (alpha-1 finite + infinity).
Points are the well-conditioned set 0, +-1, +-2, +-1/2, +-3/2, +-2/3, +-3 (taken in this order): for r=11, m=4 the fp32 error of a
whole conv layer is 3.9e-5 relative (the integer points 0, +-1 .. +-5 of the old F(2,11) give 7.7e-3), measured by running one
layer in float32 against a float64 direct convolution. Standard library only."""
import sys
from fractions import Fraction as F

PTS = [0, 1, -1, 2, -2, F(1, 2), F(-1, 2), F(3, 2), F(-3, 2), F(2, 3), F(-2, 3), 3, -3]

def toom(m, r):
    a = m + r - 1
    P = [F(p) for p in PTS[:a - 1]]
    def vand(n):
        rows = [[p ** j for j in range(n)] for p in P]
        rows.append([F(0)] * (n - 1) + [F(1)])
        return rows
    Vg, Va, Vd = vand(r), vand(m), vand(a)
    n = a
    M = [row[:] + [F(int(i == j)) for j in range(n)] for i, row in enumerate(Vd)]
    for c in range(n):
        piv = next(i for i in range(c, n) if M[i][c] != 0)
        M[c], M[piv] = M[piv], M[c]
        pv = M[c][c]; M[c] = [x / pv for x in M[c]]
        for i in range(n):
            if i != c and M[i][c] != 0:
                f = M[i][c]; M[i] = [x - f * y for x, y in zip(M[i], M[c])]
    Vinv = [row[n:] for row in M]
    AT = [[Va[i][j] for i in range(a)] for j in range(m)]
    BT = [[Vinv[j][i] for j in range(a)] for i in range(a)]
    return AT, Vg, BT

def lit(x, ctype):
    t = f"{float(x):.17g}"
    if not any(c in t for c in ".eE"): t += ".0"
    return t + ("f" if ctype == "float" else "")

def emit(name, m, r, out):
    AT, G, BT = toom(m, r)
    a = m + r - 1
    def arr(t, nm, M, ctype):
        out.write(f"static const {ctype} {nm}[{len(M)}][{len(M[0])}] = {{\n")
        for row in M:
            out.write("    {" + ", ".join(lit(x, ctype) for x in row) + "},\n")
        out.write("};\n")
    out.write(f"// F({m},{r}), alpha = {a}\nconstexpr int k{name}_M = {m}, k{name}_R = {r}, k{name}_A = {a};\n")
    arr("AT", f"k{name}_AT", AT, "float"); arr("BT", f"k{name}_BT", BT, "float"); arr("G", f"k{name}_G", G, "double")

with open(sys.argv[1], "w") as out:
    out.write("// Generated by engines/lite/engine/tools/gen_wino_tables.py: edit that script and run it again.\n#pragma once\n")
    emit("W43", 4, 3, out); emit("W47", 4, 7, out); emit("W411", 4, 11, out)
print("ok")
