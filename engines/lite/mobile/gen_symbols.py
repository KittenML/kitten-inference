"""Writes engines/lite/engine/src/capi/symbols.inc, the phoneme symbol table of the C API, from the TextCleaner class
of the Python package, so both turn the same phoneme string into the same token ids.

    python engines/lite/mobile/gen_symbols.py           # rewrite symbols.inc
    python engines/lite/mobile/gen_symbols.py --check   # exit 1 if symbols.inc is out of date

The table also holds which code points Python's re module counts as word characters (\\w) or white space (\\s), for
the blocks phonemes come from (Latin, IPA, Greek, Cyrillic, phonetic extensions, punctuation, arrows). The C API treats
other code points as word characters.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
PY_SOURCE = os.path.join(ROOT, "src", "kitten_inference", "tts08", "cpp_model.py")
OUT = os.path.join(ROOT, "engines", "lite", "engine", "src", "capi", "symbols.inc")
BLOCKS = [(0x0000, 0x0530), (0x1680, 0x1681), (0x1D00, 0x1DC0), (0x2000, 0x2200), (0x3000, 0x3001)]


def text_cleaner_table(path=PY_SOURCE):
    """symbol -> id of TextCleaner (read from the source without importing the package's native parts)."""
    with open(path, encoding="utf-8") as f:
        src = f.read()
    cls = re.search(r"^class TextCleaner:.*?(?=^\S)", src, re.S | re.M).group(0)
    ns = {}
    exec(cls, ns)  # the class only builds a dict from string constants
    return ns["TextCleaner"]().word_index_dictionary


def char_class(c):
    if re.match(r"\w", c):
        return 1
    if re.match(r"\s", c):
        return 2
    return 0


def ranges(kind):
    out = []
    for lo, hi in BLOCKS:
        start = None
        for cp in range(lo, hi):
            hit = char_class(chr(cp)) == kind
            if hit and start is None:
                start = cp
            if not hit and start is not None:
                out.append((start, cp - 1))
                start = None
        if start is not None:
            out.append((start, hi - 1))
    return out


def render():
    table = text_cleaner_table()
    lines = ["// Generated by engines/lite/mobile/gen_symbols.py from TextCleaner in",
             "// src/kitten_inference/tts08/cpp_model.py. Do not edit; run the script instead.",
             "// Symbol code point -> token id (where Python's dict keeps a later duplicate, so does this table).",
             "static const KtSymbol kSymbols[] = {"]
    lines += ["    {0x%04X, %d}," % (ord(c), i) for c, i in sorted(table.items(), key=lambda kv: ord(kv[0]))]
    lines.append("};")
    for name, kind in (("kWordRanges", 1), ("kSpaceRanges", 2)):
        lines.append("static const KtRange %s[] = {" % name)
        lines += ["    {0x%04X, 0x%04X}," % r for r in ranges(kind)]
        lines.append("};")
    lines.append("static const KtRange kCoveredBlocks[] = {")
    lines += ["    {0x%04X, 0x%04X}," % (lo, hi - 1) for lo, hi in BLOCKS]
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                print("symbols.inc is out of date: run python engines/lite/mobile/gen_symbols.py")
                return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
